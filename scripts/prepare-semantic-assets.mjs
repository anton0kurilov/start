import {build} from 'vite'
import {readFile, writeFile, mkdir, mkdtemp, rm} from 'node:fs/promises'
import {join, resolve} from 'node:path'
import {tmpdir} from 'node:os'
import {gzipSync} from 'node:zlib'
import {createHash} from 'node:crypto'

const modelDirectory = process.argv[2]
if (!modelDirectory)
    throw new Error(
        'Pass a directory prepared with scripts/ml-extract-encoder.py',
    )
const root = resolve(import.meta.dirname, '..')
const output = join(root, 'public/assets/ml/rubert-tiny-v1')
const temporary = await mkdtemp(join(tmpdir(), 'start-semantic-runtime-'))
const digest = (data) => createHash('sha256').update(data).digest('hex')
const assets = []
async function asset(path, bytes, type = 'application/octet-stream') {
    const compressed = gzipSync(bytes, {level: 9})
    const destination = join(output, path + '.gz')
    await mkdir(join(destination, '..'), {recursive: true})
    await writeFile(destination, compressed)
    assets.push({
        path,
        bytes: bytes.length,
        compressedBytes: compressed.length,
        sha256: digest(bytes),
        compressedSha256: digest(compressed),
        type,
    })
}
try {
    await build({
        configFile: false,
        publicDir: false,
        logLevel: 'error',
        build: {
            outDir: temporary,
            emptyOutDir: true,
            minify: true,
            assetsInlineLimit: 0,
            rollupOptions: {
                input: join(
                    root,
                    'node_modules/@huggingface/transformers/dist/transformers.web.js',
                ),
                preserveEntrySignatures: 'strict',
                output: {
                    entryFileNames: 'runtime.js',
                    inlineDynamicImports: true,
                },
            },
        },
    })
    await asset(
        'runtime.js',
        await readFile(join(temporary, 'runtime.js')),
        'text/javascript',
    )
    for (const file of [
        'config.json',
        'tokenizer.json',
        'tokenizer_config.json',
        'special_tokens_map.json',
        'onnx/model_quantized.onnx',
    ]) {
        const data = await readFile(join(modelDirectory, file))
        if (
            file.endsWith('.onnx') &&
            digest(data) !==
                '1d6a20cc6c15e206e91417b998bd333a06cab08116410c37e208670ca5159a7a'
        )
            throw new Error('Unexpected encoder graph hash')
        await asset(
            'model/' + file,
            data,
            file.endsWith('.json') ? 'application/json' : undefined,
        )
    }
    for (const extension of ['mjs', 'wasm'])
        await asset(
            'ort/ort-wasm-simd-threaded.asyncify.' + extension,
            await readFile(
                join(
                    root,
                    'node_modules/onnxruntime-web/dist/ort-wasm-simd-threaded.asyncify.' +
                        extension,
                ),
            ),
            extension === 'mjs' ? 'text/javascript' : 'application/wasm',
        )
    const manifest = {
        version: 'rubert-tiny-v1',
        base: '/assets/ml/rubert-tiny-v1/',
        transformers: '4.3.2',
        sourceRevision: '9a8d2ed31c37246d2a8d4d9f500dc1ca66563114',
        assets,
    }
    await writeFile(
        join(root, 'src/app/semantic-manifest.ts'),
        '// Generated by scripts/prepare-semantic-assets.mjs\nexport const semanticManifest = ' +
            JSON.stringify(manifest, null, 4) +
            ' as const\n',
    )
    await writeFile(
        join(output, 'manifest.json'),
        JSON.stringify(manifest, null, 2) + '\n',
    )
    await writeFile(
        join(output, 'NOTICE.txt'),
        'RuBERT-tiny: https://huggingface.co/cointegrated/rubert-tiny (MIT)\nEncoder-only extraction: scripts/ml-extract-encoder.py\nTransformers.js 4.3.2: https://github.com/huggingface/transformers.js (Apache-2.0)\nONNX Runtime: https://github.com/microsoft/onnxruntime (MIT)\n',
    )
    console.log(
        JSON.stringify({
            rawBytes: assets.reduce((n, a) => n + a.bytes, 0),
            downloadBytes: assets.reduce((n, a) => n + a.compressedBytes, 0),
        }),
    )
} finally {
    await rm(temporary, {recursive: true, force: true})
}
